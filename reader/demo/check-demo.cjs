// Fixture-only browser verification. Reuses installed Playwright and Chromium.
const { chromium } = require('playwright');
const { createServer } = require('node:http');
const { readFileSync, mkdirSync } = require('node:fs');
const { resolve, join } = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const file = resolve(process.argv[2] || 'reader/demo/dist/index.html');
  const evidence = resolve(process.env.PARADISE_DEMO_EVIDENCE || 'reader/demo/dist/evidence');
  mkdirSync(evidence, { recursive: true });
  const server = createServer((_req, res) => { res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' }); res.end(readFileSync(file)); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = process.env.PARADISE_DEMO_URL || `http://127.0.0.1:${server.address().port}/`;
  let browser;
  let checks = 0;
  const check = (value, message) => { assert.ok(value, message); checks++; console.log(`PASS ${message}`); };
  try {
    browser = await chromium.launch({ headless: true, ...(process.env.PARADISE_CHROMIUM ? { executablePath: process.env.PARADISE_CHROMIUM } : {}) });
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    const page = await context.newPage();
    const errors = [], requests = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    page.on('request', r => requests.push(r.url()));
    await page.goto(base);
    await page.waitForSelector('.post');
    check(await page.title() === 'Filtered feed · Demo — Paradise Reader', 'specific initial title');
    check(await page.locator('#capturedCount').innerText() === '8', 'initial sample archive loaded');
    const count = async () => page.locator('.post').count();
    const tab = name => page.getByRole('button', { name, exact: true });
    await tab('All captured').click();
    check(await count() === 8, 'all captured includes filtered and unscored originals');
    check(await page.title() === 'All captured · Demo — Paradise Reader', 'view title changes');
    check(await page.locator('[data-action="score"]').count() === 1, 'pending raw capture is visible');
    await page.locator('[data-action="score"]').click();
    check(await page.locator('[data-action="score"]').count() === 0, 'pending capture can be scored locally');
    await page.locator('[data-key="sample:6"] summary').click();
    check((await page.locator('[data-key="sample:6"] .capture-history').innerText()).includes('Captured before scoring'), 'raw capture remains in history after scoring');
    await page.locator('#threshold').evaluate(input => { input.value = '100'; input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })); });
    await tab('Filtered').click();
    check(await count() === 0 && await page.locator('#empty').isVisible(), 'strict threshold produces a usable empty state');
    await tab('All captured').click();
    check(await count() === 8, 'threshold never deletes originals');
    await tab('Saves').click();
    check(await count() === 2, 'bookmarks remain saved despite filtering');
    await page.locator('#threshold').evaluate(input => { input.value = '-100'; input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })); });
    await tab('Filtered').click();
    check(await count() === 8, 'relaxed threshold restores formerly filtered posts');
    await page.locator('[data-key="sample:0"] [data-action="save"]').click();
    await tab('Saves').click();
    check(await count() === 3, 'save action adds independent membership');
    await page.locator('#importSampleBtn').click();
    check(await page.locator('#capturedCount').innerText() === '10', 'bookmark batch dedupes existing feed item');
    check(await count() === 5, 'sample bookmark batch extends Saves');
    await page.locator('#importSampleBtn').click();
    check(await page.locator('#capturedCount').innerText() === '10', 'repeated bookmark import is idempotent');
    await page.locator('#captureBtn').click();
    check(await page.locator('#capturedCount').innerText() === '10', 'revisiting a bookmark keeps one item');
    await page.locator('#pasteBtn').click();
    await page.locator('#postText').fill('I am grateful to learn with this kind community. <img src=x onerror="window.demoUnsafe=true">');
    await page.locator('#postUrl').fill('https://x.com/demo_test/status/123456?s=20');
    await page.locator('#postSave').check();
    await page.getByRole('button', { name: 'Capture and score', exact: true }).click();
    check(await page.locator('#capturedCount').innerText() === '11', 'pasted post captured and scored');
    check(await page.evaluate(() => window.demoUnsafe) === undefined, 'pasted markup stays inert text');
    check((await page.locator('[data-key="x:123456"]').innerText()).includes('grateful'), 'pasted original displayed');
    check(await page.locator('[data-key="x:123456"] .post-link').getAttribute('href') === 'https://x.com/demo_test/status/123456', 'post link is canonicalized');
    await page.locator('#pasteBtn').click();
    await page.locator('#postText').fill('Updated original: a thoughtful insight about learning together.');
    await page.locator('#postUrl').fill('https://x.com/demo_test/status/123456');
    await page.getByRole('button', { name: 'Capture and score', exact: true }).click();
    check(await page.locator('#capturedCount').innerText() === '11', 'same real tweet ID updates without duplication');
    check(await page.locator('[data-key="x:123456"] .history-raw').count() === 2, 'changed original snapshots are retained');
    await page.locator('#search').fill('Updated original');
    check(await count() === 1, 'search narrows captured content');
    await page.reload();
    await page.waitForSelector('.post');
    check(await page.locator('#capturedCount').innerText() === '11', 'demo persists through reload');
    await tab('All captured').click();
    await page.locator('#importFile').setInputFiles({ name: 'saved.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ source: 'x-saved', mode: 'snapshot', complete: false, rows: [{ source: 'x-saved', sourceId: '987654', body: 'A locally imported bookmark', xContent: { author: { handle: 'sample_import', name: 'Sample Import' } } }] })) });
    await page.waitForFunction(() => document.getElementById('capturedCount').textContent === '12');
    check(await page.locator('#capturedCount').innerText() === '12', 'sanitized saved file imports locally');
    check(await page.locator('[data-key="x:987654"]').count() === 1, 'imported bookmark is in Saves');
    await page.locator('#importFile').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{bad-private-payload') });
    check(await page.locator('#capturedCount').innerText() === '12', 'failed import preserves existing archive');
    await page.locator('#search').fill('');
    await tab('Filtered').click();
    await page.locator('#threshold').evaluate(input => { input.value = '0'; input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })); });
    await page.screenshot({ path: join(evidence, 'demo-phone.png'), fullPage: true });
    await page.setViewportSize({ width: 320, height: 740 });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '320px view has no horizontal overflow');
    await page.locator('#pasteBtn').click();
    await page.keyboard.press('Escape');
    check(!(await page.locator('#pasteSheet').evaluate(d => d.open)), 'Escape dismisses capture dialog');
    check(await page.locator('#pasteBtn').evaluate(b => b === document.activeElement), 'dialog returns focus to capture button');
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.screenshot({ path: join(evidence, 'demo-desktop.png'), fullPage: true });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'desktop view has no overflow');
    await page.locator('#resetBtn').click();
    await page.locator('#confirmResetBtn').click();
    check(await page.locator('#capturedCount').innerText() === '8', 'reset restores sample feed');
    check(await page.locator('[data-key="x:123456"]').count() === 0, 'reset removes pasted text');
    check(errors.length === 0, `no browser or CSP errors: ${errors.join(' | ')}`);
    const origin = new URL(base).origin;
    check(requests.every(url => new URL(url).origin === origin), 'no third-party requests or live account calls');
    console.log(JSON.stringify({ status: 'passed', checks, fixtureOnly: true, widths: [320,390,1280], iPhoneTested: false, target: base }));
    await context.close();
  } finally {
    await browser?.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve));
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
