#!/usr/bin/env python3
"""Assemble the Safari copy of the web extension from the repo-root sources.

The repo root stays the single source of the extension. This script copies the
files the manifest (and the popup HTML) reference into OUT and writes a
Safari-flavoured manifest:

* background.js becomes a classic service worker: the ES-module imports at the
  top of the root background.js are inlined, because module service workers
  are not reliably supported by Safari on iOS.

Xcode runs this from a build phase of each extension target, writing straight
into the .appex resources, so the Xcode project never lists extension files.

Smoke testing: --extra-matches (or the XFP_EXTRA_MATCHES build setting) adds
match patterns to the x.com content script so a local fixture page such as
safari/fixtures/x-timeline.html gets the extension. Never use it for releases.

usage: sync-extension.py [--root REPO_ROOT] --out DIR [--extra-matches "PATTERN ..."]
"""
import argparse
import json
import os
import re
import shutil
import sys

IMPORT_RE = re.compile(r"""^\s*import\s+['"](\./[^'"]+)['"]\s*;?\s*$""")
MODULE_SYNTAX_RE = re.compile(r"^\s*(import|export)\b[\s{*'\"]", re.M)
HTML_REF_RE = re.compile(r"""(?:src|href)\s*=\s*["']([^"':#?]+)["']""", re.I)


def fail(message):
    print("sync-extension: error: " + message, file=sys.stderr)
    sys.exit(1)


def referenced_files(root, manifest):
    files = set()

    def add(rel):
        if rel and not rel.startswith(("http:", "https:", "data:", "/")):
            files.add(os.path.normpath(rel))

    for icon in (manifest.get("icons") or {}).values():
        add(icon)
    action = manifest.get("action") or {}
    for icon in (action.get("default_icon") or {}).values():
        add(icon)
    add(action.get("default_popup"))
    for script in manifest.get("content_scripts") or []:
        for rel in script.get("js", []) + script.get("css", []):
            add(rel)
    for entry in manifest.get("web_accessible_resources") or []:
        for rel in entry.get("resources", []):
            if "*" in rel:
                fail("wildcard web_accessible_resources are not supported: " + rel)
            add(rel)

    # Scripts and styles loaded by extension HTML pages (the popup).
    for page in [f for f in sorted(files) if f.endswith(".html")]:
        with open(os.path.join(root, page), encoding="utf-8") as handle:
            for rel in HTML_REF_RE.findall(handle.read()):
                add(os.path.join(os.path.dirname(page), rel))
    return files


def classic_background(root, entry):
    """Inline `import './x.js'` lines so the worker runs as a classic script."""
    with open(os.path.join(root, entry), encoding="utf-8") as handle:
        lines = handle.read().splitlines(keepends=True)
    parts = ["// Generated by safari/scripts/sync-extension.py from %s. Do not edit.\n" % entry]
    body, inlined = [], []
    for line in lines:
        match = IMPORT_RE.match(line)
        if match:
            rel = os.path.normpath(os.path.join(os.path.dirname(entry), match.group(1)))
            with open(os.path.join(root, rel), encoding="utf-8") as dep:
                source = dep.read()
            if MODULE_SYNTAX_RE.search(source):
                fail("%s uses module syntax and cannot be inlined" % rel)
            inlined.append("// ---- %s ----\n%s\n" % (rel, source))
            body.append("// (inlined above) " + line.lstrip())
        else:
            body.append(line)
    text = "".join(body)
    if MODULE_SYNTAX_RE.search(text):
        fail("%s has import/export statements other than side-effect imports" % entry)
    parts.extend(inlined)
    parts.append("// ---- %s ----\n" % entry)
    parts.append(text)
    return "".join(parts)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=os.path.normpath(os.path.join(here, "..", "..")))
    parser.add_argument("--out", required=True)
    parser.add_argument("--extra-matches", default=os.environ.get("XFP_EXTRA_MATCHES", ""),
                        help="space-separated match patterns added to the x.com content script (testing only)")
    args = parser.parse_args()

    root = os.path.abspath(args.root)
    with open(os.path.join(root, "manifest.json"), encoding="utf-8") as handle:
        manifest = json.load(handle)

    background = manifest.get("background") or {}
    worker = background.get("service_worker")
    if not worker:
        fail("manifest has no background.service_worker")

    files = referenced_files(root, manifest)
    files.discard(os.path.normpath(worker))
    os.makedirs(args.out, exist_ok=True)
    for rel in sorted(files):
        src = os.path.join(root, rel)
        if not os.path.isfile(src):
            fail("manifest references a missing file: " + rel)
        dest = os.path.join(args.out, rel)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        shutil.copyfile(src, dest)

    with open(os.path.join(args.out, worker), "w", encoding="utf-8") as handle:
        handle.write(classic_background(root, worker))

    safari = dict(manifest)
    safari["background"] = {"service_worker": worker}
    extra = args.extra_matches.split()
    if extra:
        if os.environ.get("CONFIGURATION") == "Release":
            fail("--extra-matches is for Debug smoke tests only")
        scripts = [dict(script) for script in safari["content_scripts"]]
        x_script = next(s for s in scripts if "https://x.com/*" in s.get("matches", []))
        x_script["matches"] = x_script["matches"] + extra
        safari["content_scripts"] = scripts
        print("sync-extension: WARNING test build, x.com content script also matches: " + " ".join(extra))
    with open(os.path.join(args.out, "manifest.json"), "w", encoding="utf-8") as handle:
        json.dump(safari, handle, indent=2)
        handle.write("\n")

    print("sync-extension: %d files + manifest.json -> %s (v%s)" % (len(files) + 1, args.out, manifest.get("version")))


if __name__ == "__main__":
    main()
